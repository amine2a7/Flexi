import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { describe, expect, it } from 'vitest';

// Static conventions of CLAUDE.md for the web app: tokens only (rule 18), no hard-coded text
// (rule 15 / i18n), logical properties for RTL, no browser storage of secrets (SEC-A7).
const SRC = fileURLToPath(new URL('../../src', import.meta.url));

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

const files = listFiles(SRC).filter((file) => /\.(ts|tsx|css)$/.test(file));
const rel = (file: string): string => relative(SRC, file).replaceAll('\\', '/');

function offenders(pattern: RegExp, only = /\.(ts|tsx|css)$/): string[] {
  return files
    .filter((file) => only.test(file))
    .flatMap((file) =>
      readFileSync(file, 'utf8')
        .split('\n')
        .map((line, index) => ({ line, index }))
        .filter(({ line }) => pattern.test(line))
        .map(({ index }) => `${rel(file)}:${String(index + 1)}`),
    );
}

describe('source conventions', () => {
  it('has no agent instruction file written by `next dev` (AGENTS.md, CLAUDE.md)', () => {
    // Generated by Next.js when it detects an AI agent; loaded automatically by agent tools.
    // `pnpm dev` (scripts/dev.mjs) prevents and removes them.
    const appRoot = join(SRC, '..');
    expect(['AGENTS.md', 'CLAUDE.md'].filter((name) => existsSync(join(appRoot, name)))).toEqual(
      [],
    );
  });

  it('contains source files to check', () => {
    expect(files.length).toBeGreaterThan(5);
  });

  it('has no hard-coded colour (hex, rgb, hsl)', () => {
    expect(offenders(/#[0-9a-fA-F]{3,8}\b(?![\w-])|\b(rgb|rgba|hsl|hsla)\(/)).toEqual([]);
  });

  it('has no arbitrary Tailwind value (px, rem, hex): spacing and sizes come from tokens', () => {
    expect(offenders(/\b[\w-]+-\[[^\]]+\]/, /\.tsx?$/)).toEqual([]);
  });

  it('uses logical properties only (RTL): no left/right/ml/mr/pl/pr utilities', () => {
    expect(
      offenders(
        /(?<![\w-])(?:-?(?:ml|mr|pl|pr)-|text-(?:left|right)\b|float-(?:left|right)\b|rounded-(?:l|r|tl|tr|bl|br)(?:-|\b)|border-(?:l|r)(?:-|\b)|(?:left|right)-\d)/,
        /\.tsx?$/,
      ),
    ).toEqual([]);
  });

  it('never touches browser storage or document.cookie (tokens live in HttpOnly cookies)', () => {
    expect(offenders(/\b(sessionStorage|indexedDB)\b|document\.cookie/, /\.tsx?$/)).toEqual([]);
    // One exception: the open or closed categories of the side menu (a display preference, never
    // a token nor business data), remembered per user in this browser (request of 2026-11-05).
    expect(
      offenders(/\blocalStorage\b/, /\.tsx?$/).filter(
        (place) => !place.startsWith('lib/ui/menu-state.ts:'),
      ),
    ).toEqual([]);
  });

  it('never uses eval, new Function or dangerouslySetInnerHTML', () => {
    expect(offenders(/\beval\(|new Function\(|dangerouslySetInnerHTML/, /\.tsx?$/)).toEqual([]);
  });

  it('has no console output (no sensitive data in logs, rule 9)', () => {
    expect(offenders(/\bconsole\.(log|info|debug|warn|error)\b/, /\.tsx?$/)).toEqual([]);
  });

  it('has no user-visible string literal in JSX (everything goes through i18n)', () => {
    const found = files
      .filter((file) => file.endsWith('.tsx'))
      .flatMap((file) =>
        findHardcodedText(readFileSync(file, 'utf8')).map((line) => `${rel(file)}:${String(line)}`),
      );
    expect(found).toEqual([]);
  });

  describe('the hard-coded text detector (control)', () => {
    it.each([
      ['plain JSX text', '<p>Bonjour</p>'],
      ['string in an expression', "<p>{'Bonjour'}</p>"],
      ['template literal in an expression', '<p>{`Bonjour`}</p>'],
      ['attribute string', '<button aria-label="Fermer" />'],
      ['attribute string in an expression', "<button aria-label={'Fermer'} />"],
      ['attribute template literal', '<img alt={`Logo`} />'],
    ])('flags %s', (_name, jsx) => {
      expect(findHardcodedText(`const a = ${jsx};`)).toEqual([1]);
    });

    it.each([
      ['a translation call', "<p>{t('a.b')}</p>"],
      ['whitespace only', "<p>{' '}</p>"],
      ['a class name', '<p className="text-text" />'],
      ['an identifier attribute', '<button aria-label={label} />'],
    ])('accepts %s', (_name, jsx) => {
      expect(findHardcodedText(`const a = ${jsx};`)).toEqual([]);
    });
  });
});

const TEXT_ATTRIBUTES = new Set(['aria-label', 'aria-description', 'alt', 'title', 'placeholder']);

const isTextLiteral = (node: ts.Node | undefined): boolean =>
  node !== undefined &&
  (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) &&
  node.text.trim() !== '';

/** 1-based lines of user-visible text written directly in JSX (text, `{'text'}`, text attributes). */
function findHardcodedText(sourceText: string): number[] {
  const source = ts.createSourceFile(
    'x.tsx',
    sourceText,
    ts.ScriptTarget.ES2022,
    true,
    ts.ScriptKind.TSX,
  );
  const lines: number[] = [];
  const visit = (node: ts.Node): void => {
    let hardcoded = false;
    if (ts.isJsxText(node)) hardcoded = node.text.trim() !== '';
    else if (ts.isJsxExpression(node) && !ts.isJsxAttribute(node.parent)) {
      hardcoded = isTextLiteral(node.expression);
    } else if (ts.isJsxAttribute(node) && TEXT_ATTRIBUTES.has(node.name.getText())) {
      const value = node.initializer;
      hardcoded =
        isTextLiteral(value) ||
        (value !== undefined && ts.isJsxExpression(value) && isTextLiteral(value.expression));
    }
    if (hardcoded) lines.push(source.getLineAndCharacterOfPosition(node.getStart()).line + 1);
    ts.forEachChild(node, visit);
  };
  visit(source);
  return lines;
}
